"""ComplaintPulse live console server (runs on the GPU node; tunnel the port to a laptop).

At start-up the detector runs over the stream on the GPU (K3 dedup, K1 burst cube, K2 root cause). Every decision
it makes is causal (uses only complaints up to that moment), so the console replays the stream on a simulated clock
and reveals each alert, root cause and event link at the moment it was computed. Incident briefs and customer
messages come from N-ATLaS on the same GPU, generated on demand (and cached).

    slurm/run.sh python api/server.py --port 8060 [--topics data/synthetic/topics.parquet]
"""
import argparse
import asyncio
import json
import sys
import threading
import time
from pathlib import Path

import numpy as np
import polars as pl
import uvicorn
from fastapi import FastAPI
from fastapi.responses import FileResponse, JSONResponse, StreamingResponse

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from pipeline import genai  # noqa: E402
from pipeline.detect import run as run_detector  # noqa: E402

HOUR, DAY = 3600, 86400
NICE = {"transfer_debited_not_received": "Transfer debited, not received", "reversal_delayed": "Reversal delayed",
        "wrong_beneficiary": "Wrong beneficiary", "ussd_session_timeout": "USSD session timeout", "ussd_wrong_charges": "USSD wrong charges",
        "atm_debited_no_cash": "ATM debited, no cash", "card_declined": "Card declined", "card_blocked": "Card blocked",
        "pos_debited_no_value": "POS debited, no value", "app_login_failure": "App login failure", "otp_not_received": "OTP not received",
        "app_crash": "App crash", "bvn_nin_update": "BVN/NIN update", "account_restricted": "Account restricted",
        "unauthorised_debit": "Unauthorised debit", "sms_charges": "SMS charges", "maintenance_fee": "Maintenance fee",
        "loan_deduction": "Loan deduction", "long_wait_time": "Long wait time", "staff_attitude": "Staff attitude"}
OWNER_PRIORITY = ["app_version", "switch", "telco", "atm_id", "card_scheme", "segment", "channel", "device_os", "region"]
OWNER_HINT = {"app_version": "Mobile app team", "device_os": "Mobile app team", "switch": "Switch / payments operations",
              "telco": "Digital channels (USSD)", "atm_id": "ATM operations", "card_scheme": "Card operations",
              "segment": "Product & billing", "region": "Regional operations", "channel": "Fraud & digital channels"}


class Console:
    def __init__(self, data: Path, topics: str, ops: str):
        t0 = time.perf_counter()
        self.det = run_detector(str(data), ops, topics, False)
        self.det.pop("_rows", None)
        self.detect_seconds = time.perf_counter() - t0
        df = pl.read_parquet(data / "complaints.parquet").sort("ts")
        self.meta = json.loads((data / "incidents.json").read_text())
        self.t0 = np.datetime64(self.meta["t0"])
        self.df = df
        self.ts = df["ts"].to_numpy()
        self.is_repost = (df["repost_of"] >= 0).to_numpy()
        self.lang = df["language"].to_numpy()
        self.channel = df["channel"].to_numpy()
        self.hourly = np.bincount((self.ts // HOUR).astype(int)[~self.is_repost], minlength=int(self.ts.max() // HOUR) + 1)
        self.incidents = sorted(self.det["raised"], key=lambda r: r["alert_ts"])
        self.suppressed = sorted(self.det["suppressed"], key=lambda r: r["alert_ts"])
        self.cache = {}
        bj = data / "briefs.json"
        if bj.exists():                                        # briefs pre-generated by pipeline/eval_llm.py
            for i, b in enumerate(json.loads(bj.read_text())):
                self.cache[i] = {"brief": b["brief"], "messages": b["customer_messages"], "evidence": b["evidence"]}
        self.lock = threading.Lock()
        self.speed, self.running = 3600.0, False
        self.reset()

    def reset(self):
        with self.lock:
            self.sim = 3.0 * DAY            # start after the warm-up days
            self.wall = time.perf_counter()
            self.running = False

    def now(self):
        if not self.running:
            return self.sim
        return min(self.sim + (time.perf_counter() - self.wall) * self.speed, float(self.ts.max()))

    def control(self, body):
        with self.lock:
            self.sim = self.now(); self.wall = time.perf_counter()
            if "speed" in body:
                self.speed = float(body["speed"])
            if "jump_day" in body:
                self.sim = float(body["jump_day"]) * DAY
            act = body.get("action")
            if act == "play":
                self.running = True
            elif act == "pause":
                self.running = False
        if body.get("action") == "reset":
            self.reset()

    def fmt(self, s):
        return str(self.t0 + np.timedelta64(int(s), "s")).replace("T", " ")[:16]

    def topic_label(self, t):
        return NICE.get(t, t)

    def incident_view(self, i, inc, now):
        rc = inc["root_cause"]
        top = rc[0] if rc else None
        # owner = the most operational attribute among the top explanations (a switch beats a state, etc.)
        attrs = [it.split("=")[0] for e in rc[:2] for it in e["items"]]
        owner = next((OWNER_HINT[a] for a in OWNER_PRIORITY if a in attrs), "Operations")
        return {"id": i, "title": " + ".join(self.topic_label(t) for t in inc["topics"]),
                "detected": self.fmt(inc["alert_ts"]), "age_h": (now - inc["alert_ts"]) / HOUR,
                "cause": " + ".join(top["items"]) if top else None, "lift": top["lift"] if top else None,
                "explained": top["explained"] if top else None, "event": inc["linked_event"], "owner": owner,
                "n_spike": inc["n_spike"], "expected": inc["expected"], "regions": inc["n_regions"], "channels": inc["n_channels"],
                "money": inc["money_at_stake"], "vulnerable": inc["vulnerable_share"],
                "languages": inc["languages"][:5], "priority": self.priority(inc)}

    @staticmethod
    def priority(inc):
        excess = max(inc["n_spike"] - inc["expected"], 0)
        return float(np.log1p(excess) * (1 + np.log1p(inc["money_at_stake"] / 1e6)) * (1 + inc["vulnerable_share"])
                     * (1 + 0.1 * inc["n_channels"]))

    def snapshot(self):
        with self.lock:
            now = self.now()
        i = int(np.searchsorted(self.ts, now, side="right"))
        h = int(now // HOUR)
        lo = max(0, h - 47)
        day0 = int(np.searchsorted(self.ts, now - DAY))
        recent = self.df[max(0, i - 10):i].reverse()
        langs = dict(zip(*np.unique(self.lang[day0:i], return_counts=True))) if i > day0 else {}
        revealed = [(k, inc) for k, inc in enumerate(self.incidents) if inc["alert_ts"] <= now]
        return {
            "running": self.running, "speed": self.speed, "sim_time": self.fmt(now), "sim_day": now / DAY,
            "processed": i, "reposts_collapsed": int(self.is_repost[:i].sum()),
            "last24h": int(i - day0), "languages_24h": {k: int(v) for k, v in langs.items()},
            "hourly": {"start": self.fmt(lo * HOUR), "counts": self.hourly[lo:h + 1].tolist(), "start_h": lo},
            "markers": [{"h": inc["alert_ts"] / HOUR, "id": k} for k, inc in revealed if inc["alert_ts"] / HOUR >= lo],
            "feed": [{"time": self.fmt(r["ts"]), "language": r["language"], "channel": r["channel"], "region": r["region"],
                      "text": r["text"], "repost": r["repost_of"] >= 0} for r in recent.iter_rows(named=True)],
            "incidents": [self.incident_view(k, inc, now) for k, inc in revealed][::-1],
            "suppressed": [{"topic": self.topic_label(s["topic"]), "at": self.fmt(s["alert_ts"]),
                            "excess": s["n_spike"] - s["expected"]} for s in self.suppressed if s["alert_ts"] <= now][::-1][:6],
            "detect_seconds": self.detect_seconds, "timings": self.det["timings"], "k2": self.det["k2"],
        }

    def detail(self, k):
        inc = self.incidents[k]
        view = self.incident_view(k, inc, self.now())
        rc = [{"items": e["items"], "share_spike": e["support_spike"], "share_base": e["support_base"], "lift": e["lift"],
               "explained": e["explained"]} for e in inc["root_cause"][:5]]
        c = self.cache.get(k)
        return {**view, "root_cause": rc, "samples": inc["samples"], "series": sorted(inc["series"].items(), key=lambda x: -x[1])[:6],
                "brief": c["brief"] if c else None, "messages": c["messages"] if c else {}}

    def generate(self, k, language=None):
        """Brief + customer message(s) from N-ATLaS (cached)."""
        inc = self.incidents[k]
        rc = inc["root_cause"][:3]
        ev = {"incident_id": f"I{k + 1}", "topics": [self.topic_label(t) for t in inc["topics"]],
              "detected_at": self.fmt(inc["alert_ts"]), "complaints_last_3h": inc["n_spike"], "expected_last_3h": round(inc["expected"], 1),
              "root_cause": [{"attributes": e["items"], "share_of_spike": round(e["support_spike"], 2), "share_normally": round(e["support_base"], 2),
                              "lift": round(e["lift"], 1)} for e in rc],
              "correlated_event": inc["linked_event"], "regions_affected": inc["n_regions"], "channels_affected": inc["n_channels"],
              "money_at_stake_naira": round(inc["money_at_stake"]), "languages": inc["languages"][:5],
              "sample_complaints": inc["samples"],
              "customer_facts": {"problem": " / ".join(self.topic_label(t) for t in inc["topics"]), "event": inc["linked_event"]}}
        c = self.cache.setdefault(k, {"brief": None, "messages": {}, "evidence": ev})
        if c["brief"] is None:
            c["brief"] = genai.incident_brief(ev)
        langs = [language] if language else [x["language"] for x in inc["languages"][:3]]
        for L in langs:
            if L not in c["messages"]:
                c["messages"][L] = genai.customer_message(ev, L)
        return self.detail(k)


def build_app(con: Console) -> FastAPI:
    app = FastAPI(title="ComplaintPulse live")
    dash = ROOT / "dashboard"

    @app.get("/")
    def index():
        return FileResponse(dash / "live.html")

    @app.post("/api/control")
    def control(body: dict):
        con.control(body)
        return con.snapshot()

    @app.get("/api/incident/{k}")
    def incident(k: int):
        if not 0 <= k < len(con.incidents):
            return JSONResponse({"error": "unknown incident"}, status_code=404)
        return con.detail(k)

    @app.post("/api/incident/{k}/generate")
    def generate(k: int, body: dict | None = None):
        if not 0 <= k < len(con.incidents):
            return JSONResponse({"error": "unknown incident"}, status_code=404)
        try:
            return con.generate(k, (body or {}).get("language"))
        except Exception as e:  # LLM server down or slow: say so plainly
            return JSONResponse({"error": f"N-ATLaS is not reachable ({e.__class__.__name__}). Start it with slurm/llm.sh."},
                                status_code=503)

    @app.get("/api/health")
    def health():
        return {"llm": genai.health(), "incidents": len(con.incidents)}

    @app.get("/api/stream")
    async def stream():
        async def gen():
            while True:
                yield f"data: {json.dumps(con.snapshot(), default=float)}\n\n"
                await asyncio.sleep(0.5)
        return StreamingResponse(gen(), media_type="text/event-stream", headers={"Cache-Control": "no-cache"})

    return app


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(ROOT / "data" / "synthetic"))
    ap.add_argument("--topics", default="gold")
    ap.add_argument("--ops", default="gpu")
    ap.add_argument("--host", default="0.0.0.0")
    ap.add_argument("--port", type=int, default=8060)
    args = ap.parse_args()
    print("running detector over the stream ...", flush=True)
    con = Console(Path(args.data), args.topics, args.ops)
    print(f"ready: {len(con.incidents)} incidents, {len(con.suppressed)} suppressed surges, detector {con.detect_seconds:.1f}s", flush=True)
    uvicorn.run(build_app(con), host=args.host, port=args.port, log_level="warning")


if __name__ == "__main__":
    main()
